import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const require = createRequire(new URL('../../../web/package.json', import.meta.url));
const { chromium, expect } = require('@playwright/test');
const axe = readFileSync(require.resolve('axe-core/axe.min.js'), 'utf8');
const collector = readFileSync(new URL('./collect-dom-content.js', import.meta.url), 'utf8');
const out = '/tmp/sani-time';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const results = [], captures = [], errors = [];
try {
  for (const width of [1280, 390]) for (const lang of ['zh', 'en']) for (const theme of ['light', 'dark']) {
    const page = await browser.newPage({ viewport: { width, height: 804 }, locale: lang === 'zh' ? 'zh-CN' : 'en-US' });
    page.on('pageerror', e => errors.push(e.message));
    const name = `${lang}-${theme}-${width}`, zh = lang === 'zh';
    await page.goto(`http://127.0.0.1:4313/sani/prototype-time.html?scene=r11-link-create&lang=${lang}&theme=${theme}&chrome=0&now=live`);
    const panel = page.locator('#create-panel-url'), trigger = panel.locator('.expiry > button');
    await expect(trigger).toBeVisible();
    const height = (await panel.boundingBox()).height, original = await trigger.innerText();
    async function open() { await trigger.click(); await page.getByRole('menuitemradio', {name:zh?'自定义时间…':'Pick a time…'}).click(); }
    await open();
    const pop = page.locator('.expiry-pop:popover-open');
    const time = pop.getByPlaceholder('HH:mm'), date = pop.getByPlaceholder('YYYY-MM-DD');
    const choose = pop.getByRole('button',{name:zh?'选择时间':'Choose time',exact:true});
    const menu = page.locator('.time-entry > .menu:popover-open');
    const hours = menu.locator('[data-time-column="0"]'), minutes = menu.locator('[data-time-column="1"]');
    const option = (group, n) => group.getByRole('menuitemradio',{name:n,exact:true});
    await time.fill('13:07'); await choose.click();
    await expect(option(hours,'13')).toBeFocused(); await expect(option(minutes,'07')).toHaveAttribute('aria-checked','true');
    expect((await panel.boundingBox()).height).toBe(height);
    const rect = await menu.boundingBox();
    expect(rect.x).toBeGreaterThanOrEqual(0); expect(rect.x+rect.width).toBeLessThanOrEqual(width); expect(rect.y+rect.height).toBeLessThanOrEqual(804);
    await page.evaluate(() => document.fonts.ready);
    await page.evaluate(() => Promise.all(document.getAnimations().map(a => a.finished.catch(()=>{}))));
    await page.screenshot({path:resolve(out,`${name}.png`)});
    await page.addScriptTag({content:axe});
    const violations = await page.evaluate(async () => (await axe.run(document.querySelector('.expiry-pop:popover-open'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}})).violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})));
    expect(violations).toEqual([]);
    await page.addScriptTag({content:collector});
    const capture = await page.evaluate(()=>window.__prototypeFirstUICollectDOMContent());
    capture.items = capture.items.filter(i=>/time-entry|time-columns|time-options|time-done/.test(i.location)); captures.push(capture);
    await option(hours,'23').click(); await option(minutes,'59').click(); await expect(time).toHaveValue('23:59');
    await expect(trigger).toHaveText(original);
    await page.keyboard.press('Escape'); await expect(menu).toHaveCount(0); await expect(pop).toBeVisible(); await expect(choose).toBeFocused();
    await choose.press('Enter'); await expect(option(hours,'23')).toBeFocused();
    await page.keyboard.press('Home'); await page.keyboard.press('Enter'); await expect(time).toHaveValue('00:59');
    await page.keyboard.press('ArrowRight'); await expect(option(minutes,'59')).toBeFocused();
    await page.keyboard.press('ArrowDown'); await expect(option(minutes,'00')).toBeFocused();
    await page.keyboard.press('Enter'); await expect(time).toHaveValue('00:00');
    await page.keyboard.press('End'); await expect(option(minutes,'59')).toBeFocused();
    await menu.getByRole('menuitem',{name:zh?'完成':'Done',exact:true}).click(); await expect(menu).toHaveCount(0);
    await pop.getByRole('button',{name:zh?'取消':'Cancel',exact:true}).click(); await expect(pop).toHaveCount(0); await expect(trigger).toHaveText(original);
    await open(); await date.fill('2032-02-29'); await time.fill('25:99');
    await expect(pop.getByRole('button',{name:zh?'应用时间':'Apply date and time'})).toBeDisabled();
    await choose.click(); await option(hours,'09').click(); await option(minutes,'07').click();
    await date.click(); await expect(menu).toHaveCount(0); await expect(pop).toBeVisible(); await expect(time).toHaveValue('09:07');
    await pop.getByRole('button',{name:zh?'应用时间':'Apply date and time'}).click();
    await open(); await expect(time).toHaveValue('09:07');
    await time.fill('12:34'); await time.press('Enter'); await expect(pop).toHaveCount(0);
    await open(); await expect(time).toHaveValue('12:34');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    results.push({name,pointer:true,keyboard:true,minutePrecision:true,nestedEscape:true,cancel:true,apply:true,manualEntry:true,axe:violations});
    console.log(`PASS ${name}`); await page.close();
  }
  expect(errors).toEqual([]);
  writeFileSync(resolve(out,'results.json'),JSON.stringify({results,errors},null,2));
  writeFileSync(resolve(out,'content.json'),JSON.stringify({...captures[0],items:captures.flatMap(c=>c.items)},null,2));
} finally { await browser.close(); }
